package com.example.appcontrolepro.models;

// ======================================================
// MODEL MENSALIDADE
// ======================================================
//
// UM MODEL É O "MOLDE" DOS DADOS.
//
// ESSA CLASSE REPRESENTA:
//
// ✔ MENSALIDADE DO JOGADOR
// ✔ MÊS DA MENSALIDADE
// ✔ VALOR PAGO
// ✔ STATUS
//
// USADA NA:
//
// ✔ TELA MENSALIDADES
// ✔ RELATÓRIOS
// ✔ FINANCEIRO
//
// ======================================================

// CRIA CLASSE
public class Mensalidade {

    // ======================================================
    // ID
    // ======================================================
    //
    // ID DO DOCUMENTO FIRESTORE
    //
    // ======================================================

    // ID
    private String id;

    // ======================================================
    // NOME
    // ======================================================
    //
    // NOME DO JOGADOR
    //
    // ======================================================

    // NOME
    private String nome;

    // ======================================================
    // MÊS
    // ======================================================
    //
    // GUARDA O MÊS
    //
    // EXEMPLO:
    // Maio_2026
    //
    // ======================================================

    // MÊS
    private String mes;

    // ======================================================
    // VALOR PAGO
    // ======================================================
    //
    // GUARDA O TOTAL PAGO
    //
    // ======================================================

    // VALOR PAGO
    private double valorPago;

    // ======================================================
    // CONSTRUTOR VAZIO
    // ======================================================
    //
    // FIREBASE PRECISA DESSE CONSTRUTOR
    //
    // ======================================================

    // CONSTRUTOR VAZIO
    public Mensalidade() {

    }

    // ======================================================
    // CONSTRUTOR COMPLETO
    // ======================================================
    //
    // USADO PARA CRIAR MENSALIDADE
    //
    // ======================================================

    // CONSTRUTOR
    public Mensalidade(

            String id,

            String nome,

            String mes,

            double valorPago
    ) {

        // SALVA ID
        this.id = id;

        // SALVA NOME
        this.nome = nome;

        // SALVA MÊS
        this.mes = mes;

        // SALVA VALOR
        this.valorPago = valorPago;
    }

    // ======================================================
    // GET ID
    // ======================================================
    //
    // RETORNA ID
    //
    // ======================================================

    public String getId() {

        return id;
    }

    // ======================================================
    // GET NOME
    // ======================================================
    //
    // RETORNA NOME
    //
    // ======================================================

    public String getNome() {

        return nome;
    }

    // ======================================================
    // GET MÊS
    // ======================================================
    //
    // RETORNA MÊS
    //
    // ======================================================

    public String getMes() {

        return mes;
    }

    // ======================================================
    // GET VALOR PAGO
    // ======================================================
    //
    // RETORNA VALOR PAGO
    //
    // ======================================================

    public double getValorPago() {

        return valorPago;
    }

    // ======================================================
    // SET VALOR PAGO
    // ======================================================
    //
    // ALTERA VALOR PAGO
    //
    // ======================================================

    public void setValorPago(double valorPago) {

        this.valorPago = valorPago;
    }

    // ======================================================
    // GET STATUS
    // ======================================================
    //
    // VERIFICA:
    //
    // ✔ SE PAGOU
    // ✔ OU SE ESTÁ PENDENTE
    //
    // ======================================================

    public String getStatus(){

        // ==================================================
        // SE PAGOU
        // ==================================================

        if(valorPago > 0){

            // RETORNA PAGO
            return "Pago";
        }

        // ==================================================
        // SE NÃO PAGOU
        // ==================================================

        // RETORNA PENDENTE
        return "Pendente";
    }
}